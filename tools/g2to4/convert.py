#!/usr/bin/env python3
"""ANTLR 2 (SqlScriptDOM TSql<ver>.g, C# actions) -> ANTLR 4 (C++ target) converter.

Run by the build (src/parser/CMakeLists.txt) in three steps; every step reads its inputs from the
given directories, writes only into the given output directories and rewrites a file only when
its content changes:

    convert.py grammar --grammar G --ssd DIR --ast-enums enums.hpp --out DIR --report-dir DIR
        <G>.g -> <G>Lexer.g4, <G>Parser.g4, TSqlTokens.tokens (SqlScriptDOM's token numbering),
        <G>.support.json; <report-dir>/<G>.json holds the statistics (mechanical vs hand-fixed)
    convert.py antlr --grammar G --grammar-dir DIR --out DIR --java J --antlr-jar JAR [--parts N]
        ANTLR 4 tool -> <G>Lexer.{h,cpp}, <G>Parser.h, <G>Parser.cpp (static ATN data) and
        <G>Parser_1..N.cpp (the rules, split at rule boundaries into N parts of similar size)
    convert.py support --ssd DIR --ast-enums enums.hpp --out DIR <every G.support.json>
        CodeGenerationSupporter.h, TSqlParserResource.h, Keywords.h (lexer literals table),
        ParserEnums.h, OptionHelpers.h, shared by every grammar (union over all of them)

Grammars: TSql130, TSql140, TSql150, TSql160, TSql170, TSql180, TSqlFabricDW. Names derive from
the grammar (<G>Parser/<G>Lexer; superclasses <G>ParserBase and the shared TSqlLexerBase).

Hand fixes are applied on every run, from tools/g2to4/overrides/common/ (every grammar) and
overrides/<G>/ (one grammar; wins over common):
    parser_actions.txt   C++ replacements for actions. common: `=== <rule> * sha=<hash of the C#>`
                         replaces any action of the rule with that C# text; <G>: keyed by rule +
                         action id + hash (a changed grammar invalidates the override loudly)
    parser_rules/*.g4    whole-rule ANTLR 4 replacements; a first line `// g2to4: sha=<hash>` pins
                         them to the ANTLR 2 rule (required in common: applied only where it matches)
    lexer_rules/*.g4     whole-rule replacements for the lexers
    synpreds.txt         ANTLR 2 syntactic predicates to keep (as speculative parses); all others
                         are dropped and left to ANTLR 4's unbounded lookahead (a reference to the
                         empty rule SYNPRED_MARKER marks their alternatives)
Hand-written C++ the actions call: src/parser/TSql<ver>ParserBase.cpp (the C# base class chain
TSql80 -> ... -> TSql180, TSqlFabricDW -> TSql150; drafts come from tools/g2to4/portbase.py),
src/parser/helpers/ (C# helper classes and OptionsHelper members). The output is deterministic.
"""
